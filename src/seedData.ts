// Deterministic timestamps relative to "now" so the demo always looks fresh.
const NOW = Date.now();
const H = 3600_000;
const D = 24 * H;
const iso = (msAgo: number) => new Date(NOW - msAgo).toISOString();

let actSeq = 5000;
