function mk(
  id: string, qr: string, pn: string, name: string, cat: string, vehicle: string,
  qty: number, min: number, wh: string, rack: string, shelf: string, bin: string,
  supplier: string, supPn: string, cost: number, addedAgo: number, updatedAgo: number,
  notes = '', desc = '',
): Part {
  const p: Part = {
    id, qrCode: qr, partNumber: pn, partName: name, category: cat, vehicleModel: vehicle,
    description: desc, quantity: qty, minimumStock: min, warehouse: wh, rack, shelf, bin,
    supplier, supplierPartNumber: supPn, unitCost: cost,
    dateAdded: iso(addedAgo), lastUpdated: iso(updatedAgo), notes,
  };
  void statusOf(p);
  return p;
}

